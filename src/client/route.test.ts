import { expect, test } from "vitest";
import { matchRoute } from "./route";

test.each([
  ["/", { name: "home" }],
  ["/b/abc", { name: "copy", code: "abc" }],
  ["/b/abc/", { name: "copy", code: "abc" }],
  ["/b/", { name: "not-found" }],
  ["/b", { name: "not-found" }],
  ["/b/abc/def", { name: "not-found" }],
  ["/pair", { name: "pair" }],
  ["/pair/", { name: "pair" }],
  ["/labels", { name: "labels" }],
  ["/mine", { name: "mine" }],
  ["/mine/", { name: "mine" }],
  ["/holding", { name: "holding" }],
  ["/holding/", { name: "holding" }],
  ["/members", { name: "members" }],
  ["/members/", { name: "members" }],
  ["/people", { name: "people" }],
  ["/people/", { name: "people" }],
  ["/more", { name: "more" }],
  ["/more/", { name: "more" }],
  ["/import", { name: "import" }],
  ["/import/", { name: "import" }],
  ["/collections/c1", { name: "shelf", id: "c1" }],
  ["/collections/c1/", { name: "shelf", id: "c1" }],
  ["/members/m1", { name: "member", id: "m1" }],
  ["/members/m1/", { name: "member", id: "m1" }],
  ["/copies/c1", { name: "copy-by-id", id: "c1" }],
  ["/copies/c1/", { name: "copy-by-id", id: "c1" }],
  ["/collections", { name: "not-found" }],
  ["/collections/", { name: "not-found" }],
  ["/copies/", { name: "not-found" }],
  ["/copies/a/b", { name: "not-found" }],
  ["/members/a/b", { name: "not-found" }],
  ["/nope", { name: "not-found" }],
  ["//b/abc", { name: "not-found" }],
])("%s", (path, route) => {
  expect(matchRoute(path)).toEqual(route);
});
